/* The host is the terminal. The guest gets a real slave tty from the kernel's
 * own pty code, which is what makes job control, canonical mode and SIGWINCH
 * behave; everything the program prints comes back out through this one
 * callback (mirrors what iSH's own Terminal.m does). */
static solos_ish_pty_out_cb g_pty_cb = NULL;
static void *g_pty_cb_ctx = NULL;

/* Live terminals by the id handed to the caller, so input and resize can find
 * one again without the caller holding a kernel pointer. */
#define SOLOS_MAX_PTYS 16
static struct tty *g_ptys[SOLOS_MAX_PTYS];
static pthread_mutex_t g_pty_lock = PTHREAD_MUTEX_INITIALIZER;

void solos_ish_set_pty_handler(solos_ish_pty_out_cb cb, void *ctx) {
    pthread_mutex_lock(&g_pty_lock);
    g_pty_cb = cb;
    g_pty_cb_ctx = ctx;
    pthread_mutex_unlock(&g_pty_lock);
}

static struct tty *pty_by_id(int pty_id) {
    if (pty_id < 0 || pty_id >= SOLOS_MAX_PTYS) return NULL;
    pthread_mutex_lock(&g_pty_lock);
    struct tty *tty = g_ptys[pty_id];
    pthread_mutex_unlock(&g_pty_lock);
    return tty;
}

static int solos_pty_init(struct tty *tty) {
    tty->data = NULL;
    return 0;
}

static int solos_pty_write(struct tty *tty, const void *buf, size_t len, bool blocking) {
    (void) blocking;
    pthread_mutex_lock(&g_pty_lock);
    solos_ish_pty_out_cb cb = g_pty_cb;
    void *ctx = g_pty_cb_ctx;
    pthread_mutex_unlock(&g_pty_lock);
    if (cb) cb(tty->num, (const char *) buf, (int) len, ctx);
    return (int) len;
}

static void solos_pty_cleanup(struct tty *tty) {
    pthread_mutex_lock(&g_pty_lock);
    if (tty->num >= 0 && tty->num < SOLOS_MAX_PTYS && g_ptys[tty->num] == tty)
        g_ptys[tty->num] = NULL;
    pthread_mutex_unlock(&g_pty_lock);
}

static struct tty_driver_ops solos_pty_ops = {
    .init = solos_pty_init,
    .write = solos_pty_write,
    .cleanup = solos_pty_cleanup,
};

/* Declared without DEFINE_TTY_DRIVER on purpose: pty_open_fake overwrites the
 * ttys table with the pty slave driver's own. */
static struct tty_driver solos_pty_driver = {.ops = &solos_pty_ops};

/* One end of the terminal as a file descriptor the child can hold.
 *
 * Opened through /dev/pts/<n> rather than attached as an adhoc fd, because a
 * descriptor with no path behind it is only half a terminal: the ioctls work,
 * so isatty() is happy, but ttyname() has nothing to return and anything that
 * asks which terminal it is on — `tty`, `who`, a shell deciding whether it is
 * interactive — gets the wrong answer. */
static int attach_tty_fd(struct task *task, int slot, int pty_num) {
    char path[64];
    snprintf(path, sizeof path, "/dev/pts/%d", pty_num);
    struct fd *fd = generic_open(path, O_RDWR_, 0);
    if (IS_ERR(fd)) return -1;
    task->files->files[slot] = fd;
    return 0;
}

int solos_ish_spawn_pty(const char *path,
                       const char *const *argv,
                       const char *const *envp,
                       int rows,
                       int cols,
                       solos_ish_pty *out) {
    if (!g_booted) return SOLOS_ISH_ERR_NOT_BOOTED;
    if (!path || !argv || !out) return SOLOS_ISH_ERR_ARGS;

    static char argv_buf[16384];
    static char envp_buf[16384];
    int argc = 0;

    pthread_mutex_lock(&g_lock);

    if (pack_strings(argv, argv_buf, sizeof argv_buf, &argc) < 0 ||
        pack_strings(envp, envp_buf, sizeof envp_buf, NULL) < 0) {
        pthread_mutex_unlock(&g_lock);
        return SOLOS_ISH_ERR_ARGS;
    }

    /* The task has to exist first. Allocating the pty touches the guest
     * filesystem, and that reads `current` — which is NULL on the thread this
     * call arrives on, because it has never been a guest task. */
    struct task *saved = current;
    int err = become_new_init_child();
    if (err < 0) {
        current = saved;
        pthread_mutex_unlock(&g_lock);
        return SOLOS_ISH_ERR_SPAWN;
    }
    struct task *task = current;

    struct tty *tty = pty_open_fake(&solos_pty_driver);
    if (IS_ERR(tty) || tty->num < 0 || tty->num >= SOLOS_MAX_PTYS) {
        current = saved;
        pthread_mutex_unlock(&g_lock);
        return SOLOS_ISH_ERR_SPAWN;
    }
    lock(&tty->lock);
    tty->winsize.row = (word_t) rows;
    tty->winsize.col = (word_t) cols;
    unlock(&tty->lock);

    /* Its own session, so the first open of the tty below makes it the
     * controlling terminal — without that, Ctrl-C has nowhere to go. */
    sys_setsid();

    if (attach_tty_fd(task, 0, tty->num) < 0 ||
        attach_tty_fd(task, 1, tty->num) < 0 ||
        attach_tty_fd(task, 2, tty->num) < 0) {
        current = saved;
        pthread_mutex_unlock(&g_lock);
        return SOLOS_ISH_ERR_SPAWN;
    }

    err = do_execve(path, (size_t) argc, argv_buf, envp_buf);
    if (err < 0) {
        current = saved;
        pthread_mutex_unlock(&g_lock);
        return SOLOS_ISH_ERR_EXEC;
    }

    pthread_mutex_lock(&g_pty_lock);
    g_ptys[tty->num] = tty;
    pthread_mutex_unlock(&g_pty_lock);

    out->pid = (int) task->pid;
    out->pty_id = tty->num;
    task_start(task);
    current = saved;
    pthread_mutex_unlock(&g_lock);
    return SOLOS_ISH_OK;
}

int solos_ish_pty_input(int pty_id, const char *buf, int len) {
    struct tty *tty = pty_by_id(pty_id);
    if (tty == NULL) return SOLOS_ISH_ERR_ARGS;
    /* Non-blocking: a program that is not reading must not stall the UI. */
    ssize_t n = tty_input(tty, buf, (size_t) len, 0);
    return n < 0 ? (int) n : (int) n;
}

int solos_ish_pty_resize(int pty_id, int rows, int cols) {
    struct tty *tty = pty_by_id(pty_id);
    if (tty == NULL) return SOLOS_ISH_ERR_ARGS;
    lock(&tty->lock);
    tty_set_winsize(tty, (struct winsize_){.row = (word_t) rows, .col = (word_t) cols});
    unlock(&tty->lock);
    return SOLOS_ISH_OK;
}

int solos_ish_pty_close(int pty_id) {
    struct tty *tty = pty_by_id(pty_id);
    if (tty == NULL) return SOLOS_ISH_ERR_ARGS;
    lock(&tty->lock);
    tty_hangup(tty);
    unlock(&tty->lock);
    pthread_mutex_lock(&g_pty_lock);
    if (pty_id >= 0 && pty_id < SOLOS_MAX_PTYS) g_ptys[pty_id] = NULL;
    pthread_mutex_unlock(&g_pty_lock);
    return SOLOS_ISH_OK;
}

