static solos_ish_exit_cb g_exit_cb = NULL;
static void *g_exit_ctx = NULL;

static void on_task_exit(struct task *task, int code) {
    /* Only init's direct children matter to us: deeper descendants are the
     * guest's own business, and walking them here contends with the kernel's
     * wait path for pids_lock. */
    if (task->parent != NULL && task->parent->parent != NULL) return;
    solos_ish_exit_cb cb = g_exit_cb;
    void *ctx = g_exit_ctx;
    if (cb) cb((int)task->pid, code, ctx);
}

void solos_ish_set_exit_handler(solos_ish_exit_cb cb, void *ctx) {
    g_exit_ctx = ctx;
    g_exit_cb = cb;
}

