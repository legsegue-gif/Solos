/* do_execve takes argv and envp as one NUL-separated, double-NUL-terminated
 * buffer each, because that is how the guest ABI lays them out. */
static int pack_strings(const char *const *items, char *buf, size_t cap, int *count_out) {
    size_t pos = 0;
    int count = 0;
    for (const char *const *p = items; p && *p; p++) {
        size_t len = strlen(*p) + 1;
        if (pos + len >= cap - 1) return -1;
        memcpy(buf + pos, *p, len);
        pos += len;
        count++;
    }
    buf[pos] = '\0';
    if (count_out) *count_out = count;
    return 0;
}

static int attach_pipe_fd(struct task *task, int slot, int host_fd) {
    struct fd *fd = adhoc_fd_create(&realfs_fdops);
    if (fd == NULL) return -1;
    int dup_fd = dup(host_fd);
    if (dup_fd < 0) return -1;
    fd->real_fd = dup_fd;
    task->files->files[slot] = fd;
    return 0;
}

int solos_ish_spawn(const char *path,
                   const char *const *argv,
                   const char *const *envp,
                   solos_ish_proc *out) {
    if (!g_booted) return SOLOS_ISH_ERR_NOT_BOOTED;
    if (!path || !argv || !out) return SOLOS_ISH_ERR_ARGS;

    static char argv_buf[16384];
    static char envp_buf[16384];
    int argc = 0;

    int in_pipe[2] = {-1, -1}, out_pipe[2] = {-1, -1}, err_pipe[2] = {-1, -1};
    if (pipe(in_pipe) < 0 || pipe(out_pipe) < 0 || pipe(err_pipe) < 0) {
        for (int i = 0; i < 2; i++) {
            if (in_pipe[i] >= 0) close(in_pipe[i]);
            if (out_pipe[i] >= 0) close(out_pipe[i]);
            if (err_pipe[i] >= 0) close(err_pipe[i]);
        }
        return SOLOS_ISH_ERR_PIPE;
    }

    /* `current` is thread-local and become_new_init_child overwrites it, so
     * the whole spawn runs under the lock and restores the caller's value. */
    pthread_mutex_lock(&g_lock);

    if (pack_strings(argv, argv_buf, sizeof argv_buf, &argc) < 0 ||
        pack_strings(envp, envp_buf, sizeof envp_buf, NULL) < 0) {
        pthread_mutex_unlock(&g_lock);
        goto fail;
    }

    struct task *saved = current;
    int err = become_new_init_child();
    if (err < 0) {
        current = saved;
        pthread_mutex_unlock(&g_lock);
        goto fail;
    }
    struct task *task = current;

    if (attach_pipe_fd(task, 0, in_pipe[0]) < 0 ||
        attach_pipe_fd(task, 1, out_pipe[1]) < 0 ||
        attach_pipe_fd(task, 2, err_pipe[1]) < 0) {
        current = saved;
        pthread_mutex_unlock(&g_lock);
        goto fail;
    }

    err = do_execve(path, (size_t)argc, argv_buf, envp_buf);
    if (err < 0) {
        current = saved;
        pthread_mutex_unlock(&g_lock);
        goto fail;
    }

    out->pid = (int)task->pid;
    task_start(task);
    current = saved;
    pthread_mutex_unlock(&g_lock);

    /* The guest holds its own dups; these ends belong to the child only. */
    close(in_pipe[0]);
    close(out_pipe[1]);
    close(err_pipe[1]);
    out->stdin_write = in_pipe[1];
    out->stdout_read = out_pipe[0];
    out->stderr_read = err_pipe[0];
    return SOLOS_ISH_OK;

fail:
    close(in_pipe[0]); close(in_pipe[1]);
    close(out_pipe[0]); close(out_pipe[1]);
    close(err_pipe[0]); close(err_pipe[1]);
    return SOLOS_ISH_ERR_SPAWN;
}

