/* ------------------------------------------------------------------ */
/* JIT crash recovery                                                  */
/* ------------------------------------------------------------------ */

/* Thread-locals the emulator maintains; see asbestos.c in the kernel fork. */
extern __thread volatile sig_atomic_t in_jit;
extern __thread volatile uint64_t jit_saved_pc;
extern __thread int ish_thread_marker;
extern void jit_crash_trampoline(void);
extern void (*die_handler)(const char *msg);

static void park_thread_forever(void) {
    /* pthread_exit trips SIGTRAP on iOS in some thread states, which would
     * take the whole app down. A guest thread is expendable; parking it is
     * not. */
    sigset_t all;
    sigfillset(&all);
    pthread_sigmask(SIG_BLOCK, &all, NULL);
    select(0, NULL, NULL, NULL, NULL);
    __builtin_unreachable();
}

static void jit_crash_handler(int sig, siginfo_t *info, void *ctx) {
#ifdef __aarch64__
    if ((sig == SIGSEGV || sig == SIGBUS) && in_jit) {
        /* A stale TLB pointer from a concurrent copy-on-write. Rewrite the
         * guest's saved state and resume in the trampoline, which returns
         * control to the kernel as a guest fault rather than a host crash.
         * Offsets come from the cpu-offsets.h generated by this very build,
         * never hardcoded. */
        ucontext_t *uc = (ucontext_t *)ctx;
        uint64_t cpu_ptr = uc->uc_mcontext->__ss.__x[1];
        uint64_t x7 = uc->uc_mcontext->__ss.__x[7];
        uint64_t x10 = uc->uc_mcontext->__ss.__x[10];
        uint64_t guest_addr = (x7 - x10) & 0xffffffffffffULL;
        uint64_t esr = uc->uc_mcontext->__es.__esr;
        int was_write = (esr & 0x40) != 0;

        *(uint64_t *)(cpu_ptr + CPU_segfault_addr) = guest_addr;
        *(int *)(cpu_ptr + CPU_segfault_was_write) = was_write;
        *(uint64_t *)(cpu_ptr + CPU_pc) = (uint64_t)jit_saved_pc;
        uc->uc_mcontext->__ss.__sp = *(uint64_t *)(cpu_ptr + LOCAL_jit_exit_sp);
        uc->uc_mcontext->__ss.__pc = (uint64_t)jit_crash_trampoline;

        sigset_t unblock;
        sigemptyset(&unblock);
        sigaddset(&unblock, sig);
        sigprocmask(SIG_UNBLOCK, &unblock, NULL);
        return;
    }
#endif
    if (!ish_thread_marker) {
        /* Not a guest thread: this is a genuine crash in the host app, and
         * intercepting it would hide the report. Restore and re-raise. */
        struct sigaction dfl;
        memset(&dfl, 0, sizeof dfl);
        dfl.sa_handler = SIG_DFL;
        sigaction(sig, &dfl, NULL);
        raise(sig);
        return;
    }
    char buf[192];
    int n = snprintf(buf, sizeof buf, "\n[solos-ish] guest crash: signal %d at %p\n", sig, info->si_addr);
    write(STDERR_FILENO, buf, (size_t)n);
    park_thread_forever();
}

static void solos_die_handler(const char *msg) {
    char buf[512];
    int n = snprintf(buf, sizeof buf, "\n[solos-ish] kernel die(): %s\n", msg ? msg : "(null)");
    write(STDERR_FILENO, buf, (size_t)n);
    park_thread_forever();
}

static void install_crash_handler(void) {
    static char altstack[SIGSTKSZ];
    stack_t ss;
    ss.ss_sp = altstack;
    ss.ss_size = SIGSTKSZ;
    ss.ss_flags = 0;
    sigaltstack(&ss, NULL);

    struct sigaction sa;
    memset(&sa, 0, sizeof sa);
    sa.sa_sigaction = jit_crash_handler;
    sa.sa_flags = SA_SIGINFO | SA_ONSTACK;
    sigaction(SIGSEGV, &sa, NULL);
    sigaction(SIGBUS, &sa, NULL);
    sigaction(SIGILL, &sa, NULL);
    sigaction(SIGTRAP, &sa, NULL);
    /* SIGABRT is deliberately left alone: it belongs to assert(), malloc and
     * the host runtime, and swallowing it would mask real failures. */
}

