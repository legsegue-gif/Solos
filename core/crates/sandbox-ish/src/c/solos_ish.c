static int is_descendant_of(struct task *task, pid_t_ ancestor) {
    for (struct task *t = task; t != NULL; t = t->parent) {
        if (t->pid == ancestor) return 1;
    }
    return 0;
}

int solos_ish_kill_group(int pid) {
    if (!g_booted) return SOLOS_ISH_ERR_NOT_BOOTED;
    /* pid 1 is init: killing it takes the guest down with it. */
    if (pid <= 1) return SOLOS_ISH_ERR_ARGS;

    struct siginfo_ info = SIGINFO_NIL;
    int hits = 0;
    lock(&pids_lock);
    struct task *root = pid_get_task((dword_t)pid);
    pid_t_ pgid = root ? root->group->pgid : 0;
    for (int i = 2; i < MAX_PID; i++) {
        struct task *t = pid_get_task((dword_t)i);
        if (t == NULL) continue;
        int by_pgid = (pgid != 0 && t->group->pgid == pgid);
        if (by_pgid || is_descendant_of(t, (pid_t_)pid)) {
            send_signal(t, SIGKILL_, info);
            hits++;
        }
    }
    unlock(&pids_lock);
    return hits;
}

int solos_ish_signal_all(int stop) {
    if (!g_booted) return SOLOS_ISH_ERR_NOT_BOOTED;

    struct siginfo_ info = SIGINFO_NIL;
    int signal = stop ? SIGSTOP_ : SIGCONT_;
    int hits = 0;
    lock(&pids_lock);
    /* init is left running: it reaps children, and stopping it would leave
     * exits unobserved for as long as the guest is parked. */
    for (int i = 2; i < MAX_PID; i++) {
        struct task *t = pid_get_task((dword_t)i);
        if (t == NULL) continue;
        send_signal(t, signal, info);
        hits++;
    }
    unlock(&pids_lock);
    return hits;
}

